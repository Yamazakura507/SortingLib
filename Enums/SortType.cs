namespace SortLib.Enums;

/// <summary>
/// Specifies the direction in which a sort key is ordered.
/// </summary>
public enum SortType
{
    /// <summary>
    /// Orders values from lowest to highest.
    /// </summary>
    Ascending,

    /// <summary>
    /// Orders values from highest to lowest.
    /// </summary>
    Descending
}
